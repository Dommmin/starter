import { router, useForm } from '@inertiajs/react';
import { useEffect, useState } from 'react';
import {
    Alert,
    Button,
    ConfirmDialog,
    ConflictDialog,
    PageHeader,
    ResourceForm,
    Stack,
} from '@/design-system/primitives';
import { useTranslation } from '@/i18n';
import { destroy, edit, index, store, update } from '@/routes/admin/redirects';

type EditorProps = App.Data.Admin.Redirects.RedirectEditorData;
type RecordData = App.Data.Admin.Redirects.RedirectFormData;

/** Values rendered by `ResourceForm`; keys are the request field names. */
type FormValues = {
    source_path: string;
    target: string;
    status_code: string;
    is_active: boolean;
};

const STATUS_CODES = ['301', '302'] as const;

/** Form state; identical to the rendered values (no rich text). */
type FormState = FormValues;

const FIELD_NAMES: string[] = [
    'source_path',
    'target',
    'status_code',
    'is_active',
];

function toState(record: RecordData): FormState {
    return {
        source_path: record.sourcePath ?? '',
        target: record.target ?? '',
        status_code: String(record.statusCode),
        is_active: record.isActive,
    };
}

export type RedirectFormProps = {
    editor: EditorProps;
};

/**
 * Shared create/edit screen of a redirect: one `ResourceForm`,
 * optimistic-lock conflict handling and deletion (generated by
 * `app:make-resource`). The backend normalizes both addresses and rejects
 * chains, so every redirect is a single hop.
 */
export function RedirectForm({ editor }: RedirectFormProps) {
    const record = editor.redirect;
    const recordId = record.id;
    const { can } = editor;
    const { t } = useTranslation();
    const form = useForm<FormState>(toState(record));
    const [isConflictOpen, setIsConflictOpen] = useState(false);
    const [isDeleteOpen, setIsDeleteOpen] = useState(false);
    const [isDeleting, setIsDeleting] = useState(false);

    const errors = form.errors as Partial<Record<string, string>>;
    /** Errors that no field renders inline (e.g. `updated_at`). */
    const generalErrors = Object.keys(errors)
        .filter((key) => key !== 'conflict' && !FIELD_NAMES.includes(key))
        .map((key) => errors[key] ?? '')
        .filter((message) => message !== '');

    useEffect(() => {
        if (!form.isDirty) {
            return;
        }

        return router.on('before', (event) => {
            const visit = event.detail.visit;

            if (
                visit.method !== 'get' ||
                visit.url.pathname === window.location.pathname
            ) {
                return;
            }

            if (!window.confirm(t('admin.redirects.unsavedChanges'))) {
                event.preventDefault();
            }
        });
    }, [form.isDirty, t]);

    function submit() {
        form.transform((data) => ({
            ...data,
            ...(recordId !== null
                ? { updated_at: record.updatedAt ?? '' }
                : {}),
        }));

        const options = {
            preserveScroll: true,
            onSuccess: () => form.setDefaults(),
            onError: (received: Partial<Record<string, string>>) => {
                if (received.conflict) {
                    setIsConflictOpen(true);
                }
            },
        };

        if (recordId === null) {
            form.submit(store(), options);
        } else {
            form.submit(update(recordId), options);
        }
    }

    function reloadLatest() {
        if (recordId === null) {
            return;
        }

        setIsConflictOpen(false);
        router.visit(edit.url(recordId), { preserveState: false });
    }

    function confirmDelete() {
        if (recordId === null) {
            return;
        }

        setIsDeleting(true);
        router.delete(destroy.url(recordId), {
            onFinish: () => setIsDeleting(false),
        });
    }

    return (
        <Stack gap="relaxed">
            <PageHeader
                title={
                    recordId === null
                        ? t('admin.redirects.createTitle')
                        : t('admin.redirects.editTitle')
                }
                description={t('admin.redirects.editorDescription')}
                actions={
                    recordId !== null && can.delete ? (
                        <Button
                            variant="destructive"
                            onClick={() => setIsDeleteOpen(true)}
                        >
                            {t('admin.redirects.delete')}
                        </Button>
                    ) : undefined
                }
            />

            {generalErrors.length > 0 && (
                <Alert
                    tone="danger"
                    title={t('admin.redirects.errorSummaryTitle')}
                    description={generalErrors.join(' ')}
                />
            )}

            <ResourceForm<FormValues>
                values={form.data}
                errors={errors}
                onChange={(name, value) =>
                    form.setData((data: FormState) => ({
                        ...data,
                        [name]: value,
                    }))
                }
                onSubmit={submit}
                isPending={form.processing}
                cancelHref={index()}
                labels={{
                    submit: form.processing
                        ? t('admin.redirects.saving')
                        : t('admin.redirects.save'),
                    cancel: t('admin.redirects.cancel'),
                    errorSummaryTitle: t('admin.redirects.errorSummaryTitle'),
                }}
                sections={[
                    {
                        id: 'details',
                        title: t('admin.redirects.detailsTitle'),
                        fields: [
                            {
                                type: 'text',
                                name: 'source_path',
                                label: t('admin.redirects.fields.source_path'),
                                hint: t(
                                    'admin.redirects.fields.source_pathHelp',
                                ),
                                placeholder: '/oferta/strony-www.html',
                                required: true,
                            },
                            {
                                type: 'text',
                                name: 'target',
                                label: t('admin.redirects.fields.target'),
                                hint: t('admin.redirects.fields.targetHelp'),
                                placeholder: '/kontakt',
                                required: true,
                            },
                            {
                                type: 'select',
                                name: 'status_code',
                                label: t('admin.redirects.fields.status_code'),
                                hint: t(
                                    'admin.redirects.fields.status_codeHelp',
                                ),
                                options: STATUS_CODES.map((code) => ({
                                    value: code,
                                    label: t(
                                        `admin.redirects.statuses.${code}`,
                                    ),
                                })),
                                required: true,
                            },
                            {
                                type: 'switch',
                                name: 'is_active',
                                label: t('admin.redirects.fields.is_active'),
                            },
                        ],
                    },
                ]}
            />

            {recordId !== null && (
                <ConflictDialog
                    open={isConflictOpen}
                    onOpenChange={setIsConflictOpen}
                    title={t('admin.redirects.conflictTitle')}
                    description={t('admin.redirects.conflictDescription')}
                    reloadLabel={t('admin.redirects.conflictReload')}
                    onReload={reloadLatest}
                    overwriteLabel={t('admin.redirects.cancel')}
                    onOverwrite={() => setIsConflictOpen(false)}
                />
            )}

            {recordId !== null && can.delete && (
                <ConfirmDialog
                    open={isDeleteOpen}
                    onOpenChange={setIsDeleteOpen}
                    title={t('admin.redirects.deleteTitle')}
                    description={t('admin.redirects.deleteDescription')}
                    confirmLabel={t('admin.redirects.deleteConfirm')}
                    cancelLabel={t('admin.redirects.cancel')}
                    closeLabel={t('actions.close')}
                    tone="destructive"
                    isPending={isDeleting}
                    onConfirm={confirmDelete}
                />
            )}
        </Stack>
    );
}
