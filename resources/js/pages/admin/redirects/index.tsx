import { Head, router, usePage } from '@inertiajs/react';
import { Pencil, Trash2 } from 'lucide-react';
import { useState } from 'react';
import {
    Badge,
    Button,
    ConfirmDialog,
    Inline,
    Link,
    ResourceTable,
} from '@/design-system/primitives';
import { useTranslation } from '@/i18n';
import { tableSortLabels } from '@/lib/table-sort-labels';
import { index as adminIndex } from '@/routes/admin';
import { show as importShow } from '@/routes/admin/import';
import {
    create,
    destroy,
    destroyMany,
    edit,
    index,
} from '@/routes/admin/redirects';

type Row = App.Data.Admin.Redirects.RedirectListItemData;
type IndexProps = App.Data.Admin.Redirects.RedirectIndexData;

/**
 * Admin list of managed redirects with their visit counters (generated by
 * `app:make-resource`); administrators only.
 */
export default function AdminRedirectsIndex() {
    const { items, pagination, filters, can } = usePage<IndexProps>().props;
    const { t, formatDate } = useTranslation();
    const [rowToDelete, setRowToDelete] = useState<Row | null>(null);
    const [isDeleting, setIsDeleting] = useState(false);

    const rowTitle = (row: Row) =>
        row.sourcePath || t('admin.redirects.untitled', { id: row.id });

    const deleteSelected = (keys: string[]): Promise<void> =>
        new Promise((resolve, reject) => {
            router.delete(destroyMany.url(), {
                data: { ids: keys.map(Number) },
                preserveScroll: true,
                onSuccess: () => resolve(),
                onError: () => reject(new Error('validation')),
                // Global handling still shows the HTTP or network error.
                onHttpException: () => reject(new Error('http')),
                onNetworkError: () => reject(new Error('network')),
            });
        });

    function confirmDelete() {
        if (!rowToDelete) {
            return;
        }

        setIsDeleting(true);
        router.delete(destroy.url(rowToDelete.id), {
            preserveScroll: true,
            onSuccess: () => setRowToDelete(null),
            onFinish: () => setIsDeleting(false),
        });
    }

    return (
        <>
            <Head title={t('admin.redirects.title')} />

            <ResourceTable<Row>
                url={index()}
                header={{
                    title: t('admin.redirects.title'),
                    description: t('admin.redirects.description'),
                    actions:
                        can.create || can.import ? (
                            <Inline gap="tight">
                                {can.import && (
                                    <Button
                                        variant="outline"
                                        href={importShow('redirects')}
                                    >
                                        {t('admin.import.open')}
                                    </Button>
                                )}
                                {can.create && (
                                    <Button href={create()}>
                                        {t('admin.redirects.create')}
                                    </Button>
                                )}
                            </Inline>
                        ) : undefined,
                }}
                emptyAction={
                    can.create ? (
                        <Button href={create()}>
                            {t('admin.redirects.create')}
                        </Button>
                    ) : undefined
                }
                rows={items}
                rowKey={(row) => row.id}
                pagination={pagination}
                filters={filters}
                searchable
                labels={{
                    caption: t('admin.redirects.tableCaption'),
                    sort: tableSortLabels(t),
                    searchLabel: t('admin.redirects.searchLabel'),
                    searchPlaceholder: t('admin.redirects.searchPlaceholder'),
                    searchClear: t('admin.redirects.searchClear'),
                    clearFilters: t('admin.redirects.clearFilters'),
                    emptyTitle: t('admin.redirects.emptyTitle'),
                    emptyDescription: t('admin.redirects.emptyDescription'),
                    noResultsTitle: t('admin.redirects.emptyFilteredTitle'),
                    noResultsDescription: t(
                        'admin.redirects.emptyFilteredDescription',
                    ),
                    errorTitle: t('admin.redirects.errorTitle'),
                    errorRetry: t('admin.redirects.errorRetry'),
                    previousPage: t('admin.redirects.previousPage'),
                    nextPage: t('admin.redirects.nextPage'),
                    paginationSummary: (range) =>
                        t('admin.redirects.paginationSummary', range),
                }}
                filterFields={[
                    {
                        name: 'is_active',
                        label: t('admin.redirects.fields.is_active'),
                        defaultValue: 'all',
                        options: [
                            {
                                value: 'all',
                                label: t('admin.redirects.filterAll'),
                            },
                            {
                                value: 'yes',
                                label: t('admin.redirects.active'),
                            },
                            {
                                value: 'no',
                                label: t('admin.redirects.inactive'),
                            },
                        ],
                    },
                ]}
                columns={[
                    {
                        key: 'source_path',
                        priority: 'primary',
                        label: t('admin.redirects.fields.source_path'),
                        sortable: true,
                        render: (row) => (
                            <Link href={edit(row.id)} tone="primary">
                                {rowTitle(row)}
                            </Link>
                        ),
                    },
                    {
                        key: 'target',
                        priority: 'secondary',
                        label: t('admin.redirects.fields.target'),
                        render: (row) => row.target,
                    },
                    {
                        key: 'status_code',
                        priority: 'optional',
                        label: t('admin.redirects.columnStatus'),
                        render: (row) =>
                            t(`admin.redirects.statuses.${row.statusCode}`),
                    },
                    {
                        key: 'is_active',
                        priority: 'status',
                        label: t('admin.redirects.fields.is_active'),
                        render: (row) => (
                            <Badge tone={row.isActive ? 'success' : 'neutral'}>
                                {row.isActive
                                    ? t('admin.redirects.active')
                                    : t('admin.redirects.inactive')}
                            </Badge>
                        ),
                    },
                    {
                        key: 'hits',
                        priority: 'optional',
                        label: t('admin.redirects.columnHits'),
                        sortable: true,
                        render: (row) => row.hits,
                    },
                    {
                        key: 'last_hit_at',
                        priority: 'optional',
                        label: t('admin.redirects.columnLastHit'),
                        sortable: true,
                        render: (row) =>
                            row.lastHitAt
                                ? formatDate(row.lastHitAt)
                                : t('admin.redirects.never'),
                    },
                    {
                        key: 'updated_at',
                        priority: 'optional',
                        label: t('admin.redirects.columnUpdatedAt'),
                        sortable: true,
                        render: (row) =>
                            row.updatedAt ? formatDate(row.updatedAt) : '—',
                    },
                ]}
                bulkActions={
                    can.delete
                        ? {
                              label: t('table.bulkActions'),
                              selectAllLabel: t('table.selectAll'),
                              selectRowLabel: (row) =>
                                  t('table.selectRow', {
                                      label: rowTitle(row),
                                  }),
                              selectedSummary: (count) =>
                                  t('table.selected', {}, count),
                              clearLabel: t('table.clearSelection'),
                              actions: [
                                  {
                                      id: 'delete',
                                      label: t('admin.redirects.bulkDelete'),
                                      tone: 'destructive',
                                      confirm: {
                                          title: t(
                                              'admin.redirects.bulkDeleteTitle',
                                          ),
                                          description: (count) =>
                                              t(
                                                  'admin.redirects.bulkDeleteDescription',
                                                  {},
                                                  count,
                                              ),
                                          confirmLabel: t(
                                              'admin.redirects.deleteConfirm',
                                          ),
                                          cancelLabel: t(
                                              'admin.redirects.cancel',
                                          ),
                                          closeLabel: t('actions.close'),
                                      },
                                      onRun: deleteSelected,
                                  },
                              ],
                          }
                        : undefined
                }
                rowActions={{
                    label: (row) =>
                        t('admin.redirects.rowActionsLabel', {
                            title: rowTitle(row),
                        }),
                    items: (row) => [
                        {
                            id: 'edit',
                            label: t('admin.redirects.actionEdit'),
                            icon: Pencil,
                            onSelect: () => router.visit(edit.url(row.id)),
                        },
                        ...(can.delete
                            ? [
                                  {
                                      id: 'delete',
                                      label: t('admin.redirects.actionDelete'),
                                      icon: Trash2,
                                      tone: 'destructive' as const,
                                      onSelect: () => setRowToDelete(row),
                                  },
                              ]
                            : []),
                    ],
                }}
            />

            <ConfirmDialog
                open={rowToDelete !== null}
                onOpenChange={(open) => {
                    if (!open) {
                        setRowToDelete(null);
                    }
                }}
                title={t('admin.redirects.deleteTitle')}
                description={t('admin.redirects.deleteDescription')}
                confirmLabel={t('admin.redirects.deleteConfirm')}
                cancelLabel={t('admin.redirects.cancel')}
                closeLabel={t('actions.close')}
                tone="destructive"
                isPending={isDeleting}
                onConfirm={confirmDelete}
            />
        </>
    );
}

AdminRedirectsIndex.layout = {
    breadcrumbs: [
        {
            title: 'admin.dashboard',
            href: adminIndex(),
        },
        {
            title: 'admin.redirects.title',
            href: index(),
        },
    ],
};
